const LS_LANG = 'ow_lang'
let _lang = 'en'

export function detectLang() {
  try {
    const saved = localStorage.getItem(LS_LANG)
    if (saved && DICT[saved]) return saved
    const nav = (navigator.language || 'en').slice(0, 2).toLowerCase()
    if (DICT[nav]) return nav
  } catch (_) {}
  return 'en'
}

export function getLang() { return _lang }

export function setLang(l) {
  if (!DICT[l]) return
  _lang = l
  try { localStorage.setItem(LS_LANG, l) } catch (_) {}
  try { document.documentElement.lang = l } catch (_) {}
}

export function initLang() {
  setLang(detectLang())
  return _lang
}

export function t(key, vars) {
  let str = (DICT[_lang] && DICT[_lang][key]) ?? (DICT.en[key] ?? key)
  if (vars) {
    for (const k in vars) str = str.replaceAll('{' + k + '}', vars[k])
  }
  return str
}

// Locale code for Intl/date formatting
export function localeCode() {
  return { en: 'en-US', es: 'es-ES', fr: 'fr-FR' }[_lang] || 'en-US'
}

// Translate appliance name — canonical key is French
export function ta(frName) {
  if (_lang === 'fr') return frName
  return (APPL[frName] && APPL[frName][_lang]) || frName
}

